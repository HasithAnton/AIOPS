# ─── Corrected Feature Engineering ───────────────────────────────────────────

def add_corrected_features(df: pd.DataFrame, window: int = 12) -> pd.DataFrame:
    """
    8 physically-motivated features that have genuine discriminative signal
    in the corrected dataset. All features are either absolute values or
    interface-level rolling z-scores computed from delta columns.

    Feature → fault it detects:
      latency_z       → congestion (latency 0.8ms→85ms)
      packet_loss_z   → packet_loss (loss 0.0→0.40)
      txdrop_z        → congestion + packet_loss (tx-side netem drops)
      rxdrop_z        → mtu_mismatch (rx fragment drops)
      link_down_flag  → link_failure (ifOperStatus==2, absolute)
      oper_flap_count → interface_flap (rolling std of status)
      zero_traffic_flag → link_failure (delta_in==0)
      consec_zero     → link_failure (sustained zero = blackhole)
    """
    df = df.copy()
    if 'device_id' not in df.columns:
        df['device_id'] = 'unknown'
    if 'interface_id' not in df.columns:
        df['interface_id'] = 'unknown'

    df = df.sort_values(['device_id', 'interface_id', 'timestamp']).reset_index(drop=True)
    grp = df.groupby(['device_id', 'interface_id'])
    w   = window

    # 1. Latency z-score (congestion: latency spikes significantly)
    lm = df['latency_ms']
    df['latency_z'] = (
        (lm - grp['latency_ms'].transform(lambda x: x.rolling(w, min_periods=1).mean())) /
        (grp['latency_ms'].transform(lambda x: x.rolling(w, min_periods=1).std()).fillna(0) + 1e-9)
    )

    # 2. Absolute latency value (NOT packet_loss_rate — it's 1.0 everywhere in real data)
    #    Raw latency has discriminative signal: ~0.5ms normal vs ~1500ms during faults
    df['latency_abs'] = df['latency_ms']

    # 3. High latency flag (absolute indicator: > 200ms signals congestion / path disruption)
    df['high_latency_flag'] = (df['latency_ms'] > 200.0).astype(float)

    # 4. TX discard z-score (congestion/packet_loss raise netem tx drops)
    if 'ifOutDiscards' in df.columns:
        df['delta_ifOutDiscards'] = grp['ifOutDiscards'].diff().fillna(0).clip(lower=0)
        rm = grp['delta_ifOutDiscards'].transform(lambda x: x.rolling(w, min_periods=1).mean()) + 1e-9
        rs = grp['delta_ifOutDiscards'].transform(lambda x: x.rolling(w, min_periods=1).std()).fillna(0) + 1e-6
        df['txdrop_z'] = (df['delta_ifOutDiscards'] - rm) / rs
    else:
        df['txdrop_z'] = 0.0

    # 5. RX discard z-score (mtu_mismatch: fragment drops → ifInDiscards spikes)
    if 'delta_ifInDiscards' in df.columns:
        rm2 = grp['delta_ifInDiscards'].transform(lambda x: x.rolling(w, min_periods=1).mean()) + 1e-9
        rs2 = grp['delta_ifInDiscards'].transform(lambda x: x.rolling(w, min_periods=1).std()).fillna(0) + 1e-6
        df['rxdrop_z'] = (df['delta_ifInDiscards'] - rm2) / rs2
    elif 'ifInDiscards' in df.columns:
        df['delta_ifInDiscards_c'] = grp['ifInDiscards'].diff().fillna(0).clip(lower=0)
        rm2 = grp['delta_ifInDiscards_c'].transform(lambda x: x.rolling(w, min_periods=1).mean()) + 1e-9
        rs2 = grp['delta_ifInDiscards_c'].transform(lambda x: x.rolling(w, min_periods=1).std()).fillna(0) + 1e-6
        df['rxdrop_z'] = (df['delta_ifInDiscards_c'] - rm2) / rs2
    else:
        df['rxdrop_z'] = 0.0

    # 6. Link down flag — absolute: ifOperStatus==2 (link_failure)
    df['link_down_flag'] = (df.get('ifOperStatus', 1) == 2).astype(float)

    # 7. Interface flap count — rolling std of ifOperStatus
    if 'ifOperStatus' in df.columns:
        df['oper_flap_count'] = grp['ifOperStatus'].transform(
            lambda x: x.rolling(w, min_periods=1).std()).fillna(0)
    else:
        df['oper_flap_count'] = 0.0

    # 8+9. Consecutive zero traffic (link_failure blackhole) — based on delta of raw counter
    dcol = 'delta_ifInOctets' if 'delta_ifInOctets' in df.columns else None
    if dcol is None and 'ifInOctets' in df.columns:
        df['_delta_in_raw'] = grp['ifInOctets'].diff().fillna(0).clip(lower=0)
        dcol = '_delta_in_raw'
    if dcol is not None:
        df['zero_traffic_flag'] = (df[dcol] == 0).astype(float)
        df['consec_zero'] = grp['zero_traffic_flag'].transform(
            lambda x: x.rolling(w, min_periods=1).sum())
        # 10. Delta-in z-score (traffic rate — drops to 0 during link_failure)
        rm3 = grp[dcol].transform(lambda x: x.rolling(w, min_periods=1).mean()) + 1e-9
        rs3 = grp[dcol].transform(lambda x: x.rolling(w, min_periods=1).std()).fillna(0) + 1e-6
        df['delta_in_z'] = (df[dcol] - rm3) / rs3
    else:
        df['zero_traffic_flag'] = 0.0
        df['consec_zero']       = 0.0
        df['delta_in_z']        = 0.0

    return df.fillna(0)


MN_EXTRA_FEATURES = ['latency_z', 'latency_abs', 'high_latency_flag',
                     'txdrop_z', 'rxdrop_z',
                     'link_down_flag', 'oper_flap_count',
                     'zero_traffic_flag', 'consec_zero', 'delta_in_z']


def fbeta(y_true, y_pred, beta=0.5):
    p = precision_score(y_true, y_pred, zero_division=0)
    r = recall_score(y_true, y_pred, zero_division=0)
    if p + r == 0:
        return 0.0
    return (1 + beta**2) * p * r / (beta**2 * p + r)


# ─── Data Loading ─────────────────────────────────────────────────────────────

def _clean_live_data(df: pd.DataFrame) -> pd.DataFrame:
    """
    Fix issues present in real Mininet captures:
      - Duplicate header rows embedded in data (e.g. is_anomaly == 'is_anomaly')
      - Mixed str/int types in numeric columns
    """
    # Drop rows where is_anomaly is the literal string 'is_anomaly' (dup header)
    df = df[df['is_anomaly'] != 'is_anomaly'].copy()
    df = df[df['anomaly_type'] != 'anomaly_type'].copy()

    # Cast numeric columns
    num_cols = ['ifOperStatus', 'ifInOctets', 'ifOutOctets', 'ifInDiscards',
                'ifOutDiscards', 'ifInErrors', 'latency_ms',
                'packet_loss_rate', 'cpu_utilization', 'is_anomaly']
    for col in num_cols:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors='coerce').fillna(0)

    df['is_anomaly'] = df['is_anomaly'].astype(int)
    df['anomaly_type'] = df['anomaly_type'].fillna('none')
    return df.reset_index(drop=True)


def load_and_split():
    print(f"\n[*] Loading Mininet dataset: {MININET_CSV}")
    df = pd.read_csv(MININET_CSV, low_memory=False)
    df = _clean_live_data(df)
    df['timestamp'] = pd.to_datetime(df['timestamp'], utc=True, errors='coerce')
    df = df.dropna(subset=['timestamp'])
    df = df.sort_values(['device_id', 'interface_id', 'timestamp']).reset_index(drop=True)

    total = len(df)
    anoms = int(df['is_anomaly'].sum())
    print(f"    Total records   : {total:,}")
    print(f"    Anomaly records : {anoms:,} ({anoms/total*100:.1f}%)")
    print(f"    Fault types     : {sorted(df[df['is_anomaly']==1]['anomaly_type'].unique().tolist())}")

    normal_df = df[df['is_anomaly'] == 0].copy()
    n = len(normal_df)
    train_parts = [normal_df.iloc[:int(n * 0.60)]]
    val_parts   = [normal_df.iloc[int(n * 0.60):int(n * 0.80)]]
    test_parts  = [normal_df.iloc[int(n * 0.80):]]

    for atype in df[df['is_anomaly'] == 1]['anomaly_type'].unique():
        adf = df[df['anomaly_type'] == atype].copy()
        m   = len(adf)
        train_parts.append(adf.iloc[:int(m * 0.60)])
        val_parts.append(adf.iloc[int(m * 0.60):int(m * 0.80)])
        test_parts.append(adf.iloc[int(m * 0.80):])

    # Sort by [device_id, interface_id, timestamp] — CRITICAL: this must match
    # the sort order inside add_corrected_features() so per-fault masks align
    # with y_pred row positions.
    sort_cols = ['device_id', 'interface_id', 'timestamp']
    train_df = pd.concat(train_parts).sort_values(sort_cols).reset_index(drop=True)
    val_df   = pd.concat(val_parts).sort_values(sort_cols).reset_index(drop=True)
    test_df  = pd.concat(test_parts).sort_values(sort_cols).reset_index(drop=True)

    print(f"\n    Train: {len(train_df):,} | Val: {len(val_df):,} | Test: {len(test_df):,}")
    print(f"    Train anomalies: {train_df['is_anomaly'].sum():,}")
    print(f"    Val   anomalies: {val_df['is_anomaly'].sum():,}")
    print(f"    Test  anomalies: {test_df['is_anomaly'].sum():,}")
    return train_df, val_df, test_df


def zero_flat(df: pd.DataFrame) -> pd.DataFrame:
    """Zero out features that are constant in Mininet kernel data."""
    df = df.copy()
    for feat in FLAT_FEATURES:
        if feat in df.columns:
            df[feat] = 0.0
    return df


# ─── Helpers: build feature matrix for LSTM (base + 8 corrected extras) ──────

from sklearn.preprocessing import RobustScaler as _RS

def _lstm_feature_matrix(detector, df_nf, df_mn, extra_scaler, fit=False):
    """
    Build the (N, 29) feature matrix that the LSTM actually trains/predicts on.
    Columns  0..20 : NetworkFeaturePipeline base features (robust-scaled)
    Columns 21..28 : 8 corrected extra features (extra_scaler)
    Returns (X_combined, y, df_sorted) — all three aligned to the same row order.
    """
    if fit:
        X_base, y = detector.pipeline.fit_transform(df_nf)
        detector.dl_scaler.fit(X_base)
    else:
        X_base, y = detector.pipeline.transform(df_nf)

    X_base_s = detector.dl_scaler.transform(X_base)

    if fit:
        Xe = extra_scaler.fit_transform(df_mn[MN_EXTRA_FEATURES].fillna(0).values)
    else:
        Xe = extra_scaler.transform(df_mn[MN_EXTRA_FEATURES].fillna(0).values)

    X_combined = np.hstack([X_base_s, Xe])
    return X_combined, y


# ─── LSTM Fine-Tuning ─────────────────────────────────────────────────────────

def finetune_lstm(train_df, val_df, test_df):
    print("\n" + "=" * 60)
    print("  TIER 2: Fine-Tuning LSTM-Autoencoder (29 features)")
    print("=" * 60)

    # Step 1: zero flat + add corrected absolute features to all splits
    train_nf = zero_flat(train_df)
    val_nf   = zero_flat(val_df)
    test_nf  = zero_flat(test_df)

    train_mn = add_corrected_features(train_nf)
    val_mn   = add_corrected_features(val_nf)
    test_mn  = add_corrected_features(test_nf)

    # Shared extra scaler (fitted on clean train data only)
    extra_scaler = _RS()

    # Step 2: Instantiate LSTM (input_dim will be set dynamically from X_seq shape)
    lstm = LSTMAutoencoderDetector(seq_len=10, epochs=50)

    # Step 3: Build 29-feature training matrix on CLEAN rows only
    clean_mask_tr = train_mn['is_anomaly'] == 0
    clean_tr_nf   = train_nf[clean_mask_tr].copy()
    clean_tr_mn   = train_mn[clean_mask_tr].copy()

    print(f"  Training on {len(clean_tr_nf):,} clean normal samples with 29 features...")
    X_train, _ = _lstm_feature_matrix(lstm, clean_tr_nf, clean_tr_mn, extra_scaler, fit=True)
    X_seq_tr   = lstm._create_sequences(X_train, clean_tr_nf)
    input_dim  = X_seq_tr.shape[2]   # should be 29
    print(f"  Sequence shape: {X_seq_tr.shape}  (input_dim={input_dim})")

    # Validation set (all rows) for early-stopping
    X_val, y_val = _lstm_feature_matrix(lstm, val_nf, val_mn, extra_scaler, fit=False)
    X_seq_val    = lstm._create_sequences(X_val, val_nf)

    # Step 4: Build model from scratch with correct input_dim
    from detection.lstm_autoencoder import LSTMAutoencoder
    lstm.model = LSTMAutoencoder(input_dim=input_dim).to(lstm.device)
    lstm.feature_weights = np.ones(input_dim)   # uniform weights initially
    # Boost the 8 absolute-signal columns (indices 21-28)
    ABS_BOOST = 3.0
    for i in range(21, input_dim):
        lstm.feature_weights[i] = ABS_BOOST
    lstm.feature_weights = lstm.feature_weights * input_dim / lstm.feature_weights.sum()

    optimizer  = torch.optim.Adam(lstm.model.parameters(), lr=0.001, weight_decay=1e-5)
    scheduler  = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode='min', patience=5, factor=0.5)
    criterion  = nn.MSELoss()

    # Clean val (for early stopping)
    clean_mask_val = val_mn['is_anomaly'] == 0
    X_val_clean, _ = _lstm_feature_matrix(
        lstm, val_nf[clean_mask_val].copy(), val_mn[clean_mask_val].copy(),
        extra_scaler, fit=False)
    X_seq_val_clean = lstm._create_sequences(X_val_clean, val_nf[clean_mask_val].copy())

    dataset    = TensorDataset(torch.FloatTensor(X_seq_tr))
    dataloader = DataLoader(dataset, batch_size=lstm.batch_size, shuffle=True)
    val_ds     = TensorDataset(torch.FloatTensor(X_seq_val_clean))
    val_loader = DataLoader(val_ds, batch_size=lstm.batch_size, shuffle=False)

    best_val_loss, patience_count = float('inf'), 0
    best_state = None
    EPOCHS = 60

    print(f"  Training {EPOCHS} epochs with early stopping...")
    for epoch in range(EPOCHS):
        lstm.model.train()
        total_loss = 0.0
        for (batch_x,) in dataloader:
            batch_x = batch_x.to(lstm.device)
            optimizer.zero_grad()
            out  = lstm.model(batch_x)
            loss = criterion(out, batch_x)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(lstm.model.parameters(), 1.0)
            optimizer.step()
            total_loss += loss.item()

        lstm.model.eval()
        val_total = 0.0
        with torch.no_grad():
            for (vb,) in val_loader:
                vb = vb.to(lstm.device)
                val_total += criterion(lstm.model(vb), vb).item()
        val_loss = val_total / len(val_loader)
        scheduler.step(val_loss)

        if val_loss < best_val_loss - 1e-6:
            best_val_loss  = val_loss
            patience_count = 0
            best_state = {k: v.clone() for k, v in lstm.model.state_dict().items()}
        else:
            patience_count += 1

        if (epoch + 1) % 10 == 0:
            print(f"    Epoch {epoch+1:3d}/{EPOCHS}  "
                  f"train_loss={total_loss/len(dataloader):.6f}  "
                  f"val_loss={val_loss:.6f}  "
                  f"lr={optimizer.param_groups[0]['lr']:.2e}")

        if patience_count >= 12:
            print(f"  Early stopping at epoch {epoch+1}.")
            break

    if best_state is not None:
        lstm.model.load_state_dict(best_state)
        print("  Restored best weights.")

    # Step 5: Threshold calibration on FULL val set (anomalies included)
    print("\n  Calibrating threshold on validation set (F-beta, beta=0.5)...")
    lstm.model.eval()
    mse_val_all = lstm._weighted_mse(
        torch.FloatTensor(X_seq_val).to(lstm.device),
        lstm.model(torch.FloatTensor(X_seq_val).to(lstm.device))
    ) if len(X_seq_val) <= 5000 else lstm._batched_predict_mse(X_seq_val)
    # Use batched for safety
    mse_val_all = lstm._batched_predict_mse(X_seq_val)
    mse_val_sm  = lstm._smooth_scores(mse_val_all)

    if len(np.unique(y_val)) > 1:
        best_f1, best_t_f1 = 0.0, np.percentile(mse_val_sm, 95)
        best_fb, best_t_fb = 0.0, np.percentile(mse_val_sm, 95)
        for pct in np.arange(80.0, 99.9, 0.5):
            t  = np.percentile(mse_val_sm, pct)
            p  = (mse_val_sm >= t).astype(int)
            f1 = sk_f1(y_val, p, zero_division=0)
            fb = fbeta(y_val, p, beta=0.5)
            if f1 > best_f1:  best_f1, best_t_f1 = f1, t
            if fb > best_fb:  best_fb, best_t_fb  = fb, t
        lstm.optimal_threshold = best_t_fb
        print(f"    max-F1 threshold : {best_t_f1:.6f}  (F1={best_f1:.4f})")
        print(f"    max-Fb threshold : {best_t_fb:.6f}  (Fb={best_fb:.4f})  <- USED")
    else:
        lstm.optimal_threshold = float(np.percentile(mse_val_sm, 95))
        print(f"    Threshold (95th): {lstm.optimal_threshold:.6f}")

    # Step 6: Evaluate on test set with the same 29-feature pipeline
    X_test, y_test_base = _lstm_feature_matrix(lstm, test_nf, test_mn, extra_scaler, fit=False)
    X_seq_test = lstm._create_sequences(X_test, test_nf)
    mse_test   = lstm._batched_predict_mse(X_seq_test)
    mse_test   = lstm._smooth_scores(mse_test)
    y_test     = test_df['is_anomaly'].values

    lstm_preds  = (mse_test >= lstm.optimal_threshold).astype(int)
    roc = roc_auc_score(y_test, mse_test)           if len(np.unique(y_test)) > 1 else float('nan')
    pr  = average_precision_score(y_test, mse_test) if len(np.unique(y_test)) > 1 else float('nan')
    print(f"\n  ROC-AUC : {roc:.4f}")
    print(f"  PR-AUC  : {pr:.4f}")
    print(classification_report(y_test, lstm_preds, digits=4, zero_division=0,
                                target_names=['Normal', 'Anomaly']))

    # Per-fault recall breakdown
    print("  Per-fault recall (LSTM):")
    fault_labels = test_mn['anomaly_type'].values
    for fault in sorted(test_mn['anomaly_type'].dropna().unique()):
        if fault in ('none', 'normal', '', 'nan'):
            continue
        mask = (fault_labels == fault)
        if mask.sum() == 0 or y_test[mask].sum() == 0:
            continue
        r = recall_score(y_test[mask], lstm_preds[mask], zero_division=0)
        p_s = precision_score(y_test[mask], lstm_preds[mask], zero_division=0)
        print(f"    {fault:20s}  recall={r:.3f}  precision={p_s:.3f}")

    # Attach the extra_scaler so predict() can be called later
    lstm._extra_scaler   = extra_scaler
    lstm._use_extra_feats = True

    return lstm, {'roc_auc': roc, 'pr_auc': pr}


# ─── Random Forest Domain Adaptation ─────────────────────────────────────────

def adapt_random_forest(train_df, val_df, test_df):
    print("\n" + "=" * 60)
    print("  TIER 1: Domain-Adapting Random Forest")
    print("=" * 60)

    # --- Feature engineering ---
    # Use NetworkFeaturePipeline (proven, avoids cumulative counter drift)
    # + inject 5 Mininet-specific features on top

    # Zero flat features then compute corrected feature set
    train_z  = zero_flat(train_df)
    val_z    = zero_flat(val_df)
    test_z   = zero_flat(test_df)

    train_mn = add_corrected_features(train_z)   # also re-sorts by [dev,intf,ts]
    val_mn   = add_corrected_features(val_z)
    test_mn  = add_corrected_features(test_z)

    # Fit NetworkFeaturePipeline on sorted train
    pipe = NetworkFeaturePipeline()
    X_train_base, y_train = pipe.fit_transform(train_mn)
    X_val_base,   y_val   = pipe.transform(val_mn)
    X_test_base,  y_test  = pipe.transform(test_mn)

    # Scale the 8 corrected extra features
    from sklearn.preprocessing import RobustScaler
    extra_scaler = RobustScaler()
    Xe_train = extra_scaler.fit_transform(train_mn[MN_EXTRA_FEATURES].fillna(0).values)
    Xe_val   = extra_scaler.transform(val_mn[MN_EXTRA_FEATURES].fillna(0).values)
    Xe_test  = extra_scaler.transform(test_mn[MN_EXTRA_FEATURES].fillna(0).values)

    X_train = np.hstack([X_train_base, Xe_train])
    X_val   = np.hstack([X_val_base,   Xe_val])
    X_test  = np.hstack([X_test_base,  Xe_test])

    print(f"    Features: {X_train_base.shape[1]} base + {Xe_train.shape[1]} Mininet-extra = {X_train.shape[1]} total")
    print(f"    Train: {len(X_train):,} samples ({int(y_train.sum()):,} anomaly)")

    # --- SMOTE with mild ratio (0.3 not 1.0) to reduce synthetic noise ---
    from imblearn.over_sampling import SMOTE
    if y_train.sum() > 5:
        k      = min(5, int(y_train.sum()) - 1)
        n_norm = int((y_train == 0).sum())
        n_target = int(n_norm * 0.3)   # target anomaly count = 30% of normal
        n_target = max(n_target, int(y_train.sum()))  # don't reduce
        sm = SMOTE(random_state=42, k_neighbors=k,
                   sampling_strategy=min(n_target / n_norm, 1.0))
        X_train, y_train = sm.fit_resample(X_train, y_train)
        print(f"    SMOTE (ratio 0.3) -> {len(X_train):,} samples ({int(y_train.sum()):,} anomaly)")

    # --- RF with controlled depth to prevent overfitting on SMOTE data ---
    from sklearn.ensemble import RandomForestClassifier
    clf = RandomForestClassifier(
        n_estimators=500,
        max_depth=15,              # deeper than v3 — corrected data has clean signals
        min_samples_leaf=3,
        min_samples_split=6,
        max_features='sqrt',
        class_weight='balanced_subsample',
        bootstrap=True,
        oob_score=True,
        random_state=42,
        n_jobs=-1,
    )
    clf.fit(X_train, y_train)
    print(f"    [OK] RF trained: 500 trees, max_depth=15, OOB={clf.oob_score_:.4f}")

    # --- Threshold search with precision guard ---
    # Only consider thresholds where val precision >= MIN_PREC
    # This prevents the threshold from collapsing to 0.10 when the model
    # can't separate classes well (causing 80% of normals flagged as anomaly)
    val_proba = clf.predict_proba(X_val)[:, 1]
    MIN_PREC  = 0.10   # real Mininet data has weaker signals — allow lower precision for recall

    best_f1,   best_t_f1 = 0.0, 0.5
    best_fb,   best_t_fb = 0.0, 0.5

    for t in np.arange(0.10, 0.91, 0.02):
        p_arr = (val_proba >= t).astype(int)
        prec  = precision_score(y_val, p_arr, zero_division=0)
        if prec < MIN_PREC:
            continue   # skip thresholds that flood false positives
        f1 = sk_f1(y_val, p_arr, zero_division=0)
        fb = fbeta(y_val, p_arr, beta=0.5)
        if f1 > best_f1:  best_f1, best_t_f1 = f1, t
        if fb > best_fb:  best_fb, best_t_fb  = fb, t

    # Fallback: if no threshold meets precision guard, use max-F1 without guard
    if best_t_f1 == 0.5 and best_f1 == 0.0:
        print("    [!] Precision guard too strict — falling back to unconstrained F1 search")
        for t in np.arange(0.10, 0.91, 0.02):
            p_arr = (val_proba >= t).astype(int)
            f1    = sk_f1(y_val, p_arr, zero_division=0)
            if f1 > best_f1:
                best_f1, best_t_f1 = f1, t
        best_t_fb, best_fb = best_t_f1, best_f1

    print(f"    max-F1 threshold : {best_t_f1:.2f}  (Val F1={best_f1:.4f})")
    print(f"    max-Fb threshold : {best_t_fb:.2f}  (Val Fb={best_fb:.4f})  <- USED")
    best_thresh = best_t_fb

    # --- Test evaluation ---
    y_prob = clf.predict_proba(X_test)[:, 1]
    y_pred = (y_prob >= best_thresh).astype(int)

    roc = roc_auc_score(y_test, y_prob)           if len(np.unique(y_test)) > 1 else float('nan')
    pr  = average_precision_score(y_test, y_prob) if len(np.unique(y_test)) > 1 else float('nan')
    print(f"\n  ROC-AUC : {roc:.4f}")
    print(f"  PR-AUC  : {pr:.4f}")
    print(classification_report(y_test, y_pred, digits=4, zero_division=0,
                                target_names=['Normal', 'Anomaly']))

    # Per-fault recall — use test_mn (sorted by [dev,intf,ts]) for the mask
    # so row positions align with y_pred (which follows test_mn's order).
    print("  Per-fault recall:")
    fault_labels = test_mn['anomaly_type'].values   # aligned with y_pred
    for fault in sorted(test_mn['anomaly_type'].unique()):
        if fault in ('none', 'normal', ''):
            continue
        mask = (fault_labels == fault)
        if mask.sum() == 0:
            continue
        r   = recall_score(y_test[mask], y_pred[mask], zero_division=0)
        p_s = precision_score(y_test[mask], y_pred[mask], zero_division=0)
        n_anom = int(y_test[mask].sum())
        print(f"    {fault:20s}  recall={r:.3f}  precision={p_s:.3f}  (n_anom={n_anom})")

    rf_bundle = {
        'clf':           clf,
        'pipeline':      pipe,
        'extra_scaler':  extra_scaler,
        'threshold':     best_thresh,
        'mn_features':   MN_EXTRA_FEATURES,
        'flat_features': FLAT_FEATURES,
    }
    return rf_bundle, {'roc_auc': roc, 'pr_auc': pr}


